-- =========================================
-- TABELA BANCO
-- =========================================
CREATE TABLE BANCO (
    COD_BANCO NUMBER(3) NOT NULL,
    CNPJ NUMBER(15) NOT NULL,
    RAZAO_SOCIAL VARCHAR2(60) NOT NULL,
    NOME_FANTASIA VARCHAR2(60),
    DATA_ABERTURA DATE NOT NULL,
    DATA_FECHAMENTO DATE,
    LOGRADOURO VARCHAR2(60) NOT NULL,

    CONSTRAINT BANCO_PK PRIMARY KEY (COD_BANCO)
);

COMMENT ON TABLE BANCO IS
'Tabela responsável por armazenar informações cadastrais das instituições financeiras';

