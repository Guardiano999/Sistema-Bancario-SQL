-- =========================================
-- TABELA CONTA_CORRENTE
-- =========================================
CREATE TABLE CONTA_CORRENTE (
    COD_BANCO NUMBER(3) NOT NULL,
    COD_AGENCIA NUMBER(5) NOT NULL,
    NUMERO_CONTA NUMBER(7) NOT NULL,
    DATA_ABERTURA DATE NOT NULL,
    NOME_CORRENTISTA VARCHAR2(60) NOT NULL,
    LIMITE_CHEQUE NUMBER(7,2),

    CONSTRAINT CONTA_CORRENTE_PK
        PRIMARY KEY (COD_BANCO, COD_AGENCIA, NUMERO_CONTA),

    CONSTRAINT CONTA_CORRENTE_BANCO_FK
        FOREIGN KEY (COD_BANCO)
        REFERENCES BANCO(COD_BANCO),

    CONSTRAINT CONTA_CORRENTE_AGENCIA_FK
        FOREIGN KEY (COD_BANCO, COD_AGENCIA)
        REFERENCES AGENCIA(COD_BANCO, COD_AGENCIA)
);

