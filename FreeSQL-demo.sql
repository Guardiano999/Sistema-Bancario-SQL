-- =========================================
-- TABELA AGENCIA
-- =========================================
CREATE TABLE AGENCIA (
    COD_BANCO NUMBER(3) NOT NULL,
    COD_AGENCIA NUMBER(5) NOT NULL,
    NOME_AGENCIA VARCHAR2(60) NOT NULL,
    LOGRADOURO VARCHAR2(60) NOT NULL,

    CONSTRAINT AGENCIA_PK PRIMARY KEY (COD_BANCO, COD_AGENCIA),
    CONSTRAINT AGENCIA_BANCO_FK FOREIGN KEY (COD_BANCO)
        REFERENCES BANCO(COD_BANCO)
